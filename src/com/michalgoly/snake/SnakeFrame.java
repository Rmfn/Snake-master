package com.michalgoly.snake;

import java.awt.EventQueue;
import java.awt.GridBagLayout;
import java.awt.event.KeyAdapter;
import java.awt.event.KeyEvent;

import javax.swing.JFrame;
import javax.swing.JOptionPane;

import com.horstmann.corejava.GBC;
import com.michalgoly.snake.Facade.GameFacade;
import com.michalgoly.snake.builder.ConcreteGameConfigBuilder;
import com.michalgoly.snake.builder.GameConfig;
import com.michalgoly.snake.state.GameState;
import com.michalgoly.snake.state.GameOverState;
import com.michalgoly.snake.state.ReadyState;
// import com.michalgoly.snake.facade.GameFacade;

/**
 * SnakeFrame initializes and lays out other GUI componnets within itself. It
 * also constructs the snake object and prepares the game thread, which will be 
 * started later on, when a user presses one of the arrow keys. 
 * 
 * @author Michal Goly
 */
public class SnakeFrame extends JFrame {
	
	private ScorePanel scorePanel;
	private GameField gameField;
	// private Thread thread;
	// private Snake snake;
	private GameFacade gameFacade;
	//  private Runnable game;

private GameConfig config = new ConcreteGameConfigBuilder()
							.setPanelHeight(400)
							.setPanelWidth(400)
							.setDelay(200)
							.build();

	// Current direction of the snake
	private Direction direction = Direction.UP;
	
	private GameState state;
	
	/**
	 * This constructor initializes GUI components, game thread and the frame
	 * itself.
	 */
	public SnakeFrame() {
		initComponents();
		initGame();
		setState(new ReadyState());
		initFrame();	
	}
	
	private void initComponents() {
		setLayout(new GridBagLayout());
		addKeyListener(new KeyboardHandler());
		
		scorePanel = new ScorePanel();
		add(scorePanel, new GBC(0, 8, 8, 1));
		
		gameField = new GameField(config);
		add(gameField, new GBC(0, 0, 8, 8));

	}
	
	// private void initGame() {
	// 	snake = new Snake(gameField, scorePanel);
	// 	Runnable r = new Game(gameField, snake, this, config);
	// 	thread = new Thread(r);
	// }
	//reemmm facade (before and after of initgame)
	 private void initGame() {
        gameFacade = new GameFacade(
                gameField,
                scorePanel,
                this,
                config
        );
    }
	
	private void initFrame() {
		pack();
		setTitle("Snake");
		setLocationRelativeTo(null);
		setDefaultCloseOperation(JFrame.EXIT_ON_CLOSE);
		setResizable(false);
		setVisible(true);
	}

	//Context methods used by the concrete states

	public void setState(GameState state) {
		this.state = state;
		gameField.setStatusText(state.getStatusText());
	}

	public void startGame() {
		gameFacade.startGame();
	}

	public void changeDirection(Direction direction) {
		this.direction = direction;
		gameFacade.changeDirection(direction);
	}

	public Direction getDirection() {
		return direction;
	}

	public void pauseGame() {
		gameFacade.pauseGame();
	}

	public void resumeGame() {
		gameFacade.resumeGame();
	}
	
	/**
	 * Called by Game on the game thread when the snake dies.
	 * The state and the dialog must change on the Swing thread (EDT).
	 */
	public void gameOver() {
		EventQueue.invokeLater(() -> {
			setState(new GameOverState());
			showGameOverDialog();
		});
	}

	/**
	 * Lets the user decide whether he wants to continue to play.
	 */
	private void showGameOverDialog() {
		int returnValue = JOptionPane.showConfirmDialog(this,
				"Do you want to start a new game?", "GAME OVER!", JOptionPane
				.OK_CANCEL_OPTION, JOptionPane.WARNING_MESSAGE);

		if (returnValue == JOptionPane.CANCEL_OPTION) {
			System.exit(0);
		} else {
			// OK, or the dialog was closed with X: start again
			gameFacade.restartGame();
			direction = Direction.UP;
			setState(new ReadyState());
		}
	}
	
	// The entry point of the game
	public static void main(String[] args) {
		/*
		 * Because Swing is not thread safe we have to run the code within the
		 * event dispatch thread. You can find out more 
		 * <a href="https://docs.oracle.com/javase/tutorial/uiswing/concurrency/dispatch.html">here</a>
		 */
		EventQueue.invokeLater(new Runnable() {
			
			@Override
			public void run() {
				new SnakeFrame();
			}
		});
	}
	
	/*
	 * Acts as a KeyListener and responds to the events generated by one of the 4
	 * arrow keys, whenever they are pressed.
	 */
	private class KeyboardHandler extends KeyAdapter {
		
				@Override
		public void keyPressed(KeyEvent e) {
			switch (e.getKeyCode()) {
				case KeyEvent.VK_UP:
					state.arrowPressed(SnakeFrame.this, Direction.UP);
					break;
				case KeyEvent.VK_DOWN:
					state.arrowPressed(SnakeFrame.this, Direction.DOWN);
					break;
				case KeyEvent.VK_LEFT:
					state.arrowPressed(SnakeFrame.this, Direction.LEFT);
					break;
				case KeyEvent.VK_RIGHT:
					state.arrowPressed(SnakeFrame.this, Direction.RIGHT);
					break;
				case KeyEvent.VK_P:
					state.pausePressed(SnakeFrame.this);
					break;
				default:
					break;
			}
		}
}
}

